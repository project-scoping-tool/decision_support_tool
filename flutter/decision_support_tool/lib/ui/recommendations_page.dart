/// Page for selecting recommendations
class RecommendationsPage extends StatefulWidget {
  const RecommendationsPage({super.key, required this.viewModel});

  final RecommendationsViewModel viewModel;

  @override
  State<RecommendationsPage> createState() => _RecommendationsPageState();
}

class _RecommendationsPageState extends State<RecommendationsPage> {
  static const String title = 'Step 3:     Select Proposed Infrastructure';
  static const String s3_disclaimer =
      'The health-promoting features recommended for this project are highlighted below. These recommendations are based on answers to questions in Steps 1 & 2. They are intended to promote walkability and bikeability and to reduce crashes in a targeted manner. Please consider these recommendations in your project design decisions.\n\nTo complete Step 3, please choose the features that you plan to include in the project. You are highly encouraged to select features that correspond to the recommendations generated by this tool. However, you may choose not to follow a recommendation (i.e., select a feature that is not recommended or select not to include a recommended feature), if you believe a specific recommendation is inappropriate for this particular project. If you choose not to follow a recommendation, please use the "write-in" column tilted "Justification" to explain why you are choosing not to follow a recommendation and what you are choosing instead and why.';

  RecommendationsViewModel get _viewModel => widget.viewModel;
  String get _jurisdiction => widget.viewModel.assessmentInfo.jurisdiction;

  // Text controllers for justification fields
  late List<TextEditingController> _justificationControllers;

  // Radio values structure: [categoryIndex][columnType (0=Good, 1=Better, 2=Best)][optionIndex]
  late List<List<List<int>>> _radioValues;
  late List<List<int>> numRadio;

  // Max character lengths for each category
  final List<int> maxLength = [75, 195, 195, 570, 375, 180, 435, 405, 135];

  @override
  void initState() {
    super.initState();

    // Initialize text controllers for each category
    _justificationControllers = List.generate(
      _viewModel.recommendationsInfo.s3_categories.length,
      (index) =>
          TextEditingController(text: _viewModel.justifications[index].value),
    );

    // Add listeners to update the view model when text changes
    for (var i = 0; i < _justificationControllers.length; i++) {
      final controller = _justificationControllers[i];
      final categoryIndex = i;
      controller.addListener(() {
        _viewModel.setJustification(categoryIndex, controller.text);
      });
    }

    // Initialize radio values structure
    _initializeRadioValues();

    // Log the recommended value when the page initializes
    WidgetsBinding.instance.addPostFrameCallback((_) {
      final recommendedValue =
          _viewModel.infrastructureRecommendation.recommendedText;
      print('Recommended Infrastructure (Step 3): $recommendedValue');
    });
  }

  void _initializeRadioValues() {
    numRadio = [];
    _radioValues = [];

    for (
      var i = 0;
      i < _viewModel.recommendationsInfo.s3_categories.length;
      i++
    ) {
      final category = _viewModel.recommendationsInfo.s3_categories[i];

      numRadio.add([
        category.goodHealth.length,
        category.betterHealth.length,
        category.bestHealth.length,
      ]);

      _radioValues.add([]);
      for (var j = 0; j < 3; j++) {
        _radioValues[i].add(List<int>.filled(numRadio[i][j], -1));
      }
    }
  }

  @override
  void dispose() {
    for (var controller in _justificationControllers) {
      controller.dispose();
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: _buildWidgetAppBarTitle(title, _jurisdiction),
        automaticallyImplyLeading: false,
      ),
      // This page is built once and never rebuilt by page navigation
      // itself (AssessmentApp scrolls between pages via PageController,
      // not setState), so without this the recommendation/labels shown
      // here would stay frozen at whatever they were the first time this
      // page was reached — even after going back and changing a Step 1/2
      // answer. Rebuilding on answersChanged keeps it in sync.
      body: ListenableBuilder(
        listenable: _viewModel.answersChanged,
        builder: (context, _) => _buildWidgetBody(),
      ),
    );
  }

