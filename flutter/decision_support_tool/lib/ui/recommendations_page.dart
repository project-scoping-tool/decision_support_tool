        crossAxisAlignment: CrossAxisAlignment.stretch,
        mainAxisSize: MainAxisSize.min,
        mainAxisAlignment: MainAxisAlignment.center,
        children: [
          // Text field
          TextField(
            controller: _justificationControllers[categoryIndex],
            maxLines: null,
            minLines: 1,
            maxLength: maxLength[categoryIndex],
            decoration: InputDecoration(
              hintText: 'Enter justification...',
              border: OutlineInputBorder(
                borderSide: BorderSide(color: Colors.grey),
              ),
              enabledBorder: OutlineInputBorder(
                borderSide: BorderSide(color: Colors.grey[400]!),
              ),
              focusedBorder: OutlineInputBorder(
                borderSide: BorderSide(color: Colors.blue, width: 2.0),
              ),
              contentPadding: EdgeInsets.symmetric(
                horizontal: 12.0,
                vertical: 8.0,
              ),
              counterText: '', // Hide default counter
              filled: true,
              fillColor: Colors.white,
            ),
            style: TextStyle(fontSize: 14.0),
            onChanged: (text) {
              setState(() {}); // Update character count
            },
          ),
          // Character counter right below the text field
          Padding(
            padding: EdgeInsets.only(top: 4.0, right: 4.0),
            child: Align(
              alignment: Alignment.centerRight,
              child: Text(
                '${_justificationControllers[categoryIndex].text.length}/${maxLength[categoryIndex]}',
                style: TextStyle(fontSize: 12.0, color: Colors.grey[600]),
              ),
            ),
          ),
        ],
      ),
    );
  }

  // Logic for mutual exclusivity between radio buttons
  void _logicRadioValues(String category, int row, int column) {
    int index;
    if (category == 'good')
      index = 0;
    else if (category == 'better')
      index = 1;
    else
      index = 2;

    // Question 1 (Speed Limit)
    if (row == 0) {
      if (index == 0) {
        _radioValues[0][1][0] = -1;
        _radioValues[0][2][0] = -1;
      } else if (index == 1) {
        _radioValues[0][0][0] = -1;
        _radioValues[0][2][0] = -1;
      } else {
        _radioValues[0][0][0] = -1;
        _radioValues[0][1][0] = -1;
      }
    }
    // Question 2 (Traffic Calming)
    else if (row == 1) {
      if (column == 0) {
        if (index == 0) {
          _radioValues[1][1][0] = -1;
          _radioValues[1][2][0] = -1;
        } else if (index == 1) {
          _radioValues[1][0][0] = -1;
          _radioValues[1][2][0] = -1;
        } else {
          _radioValues[1][0][0] = -1;
          _radioValues[1][1][0] = -1;
        }
      } else if (column == 1 && index == 1) {
        _radioValues[1][2][2] = -1;
      } else if (column == 2 && index == 2) {
        _radioValues[1][1][1] = -1;
      } else if (column == 2 && index == 1) {
        _radioValues[1][2][3] = -1;
      } else if (column == 3 && index == 2) {
        _radioValues[1][1][2] = -1;
      }
    }
    // Question 3 (Sidewalks)
    else if (row == 2) {
      if (column == 0) {
        if (index == 0) {
          _radioValues[2][1][0] = -1;
          _radioValues[2][2][0] = -1;
        } else if (index == 1) {
          _radioValues[2][0][0] = -1;
          _radioValues[2][2][0] = -1;
        } else if (index == 2) {
          _radioValues[2][0][0] = -1;
          _radioValues[2][1][0] = -1;
        }
      } else if (column == 1 && index == 0) {
        _radioValues[2][1][1] = -1;
        _radioValues[2][2][1] = -1;
      } else if (column == 1 && index == 1) {
        _radioValues[2][0][1] = -1;
        _radioValues[2][2][1] = -1;
      } else if (column == 1 && index == 2) {
        _radioValues[2][0][1] = -1;
        _radioValues[2][1][1] = -1;
      } else if (column == 2 && index == 0) {
        _radioValues[2][1][2] = -1;
        _radioValues[2][2][2] = -1;
      } else if (column == 2 && index == 1) {
        _radioValues[2][0][2] = -1;
        _radioValues[2][2][2] = -1;
      } else if (column == 2 && index == 2) {
        _radioValues[2][0][2] = -1;
        _radioValues[2][1][2] = -1;
      } else if (column == 3 && index == 1) {
        _radioValues[2][2][3] = -1;
      } else if (column == 3 && index == 2) {
        _radioValues[2][1][3] = -1;
      }
    }
    // Question 4 (Crosswalks & Signalized Intersections)
    else if (row == 3) {
      // blue
      if (column == 0 && index == 0) {
        _radioValues[3][1][0] = -1;
      } else if (column == 0 && index == 1) {
        _radioValues[3][0][0] = -1;
      }
      // red
      else if (column == 0 && index == 2) {
        _radioValues[3][1][2] = -1;
      } else if (column == 2 && index == 1) {
        _radioValues[3][2][0] = -1;
      }
      // purple
      else if (column == 1 && index == 0) {
        _radioValues[3][1][1] = -1;
        _radioValues[3][2][1] = -1;
      } else if (column == 1 && index == 1) {
        _radioValues[3][0][1] = -1;
        _radioValues[3][2][1] = -1;
      } else if (column == 1 && index == 2) {
        _radioValues[3][0][1] = -1;
        _radioValues[3][1][1] = -1;
      }
      // green
      else if (index == 1 && column == 4) {
        _radioValues[3][2][3] = -1;
      } else if (index == 2 && column == 3) {
        _radioValues[3][1][4] = -1;
      }
      // orange
      else if (index == 1 && column == 3) {
        _radioValues[3][2][4] = -1;
      } else if (index == 2 && column == 4) {
        _radioValues[3][1][3] = -1;
      }
      // magenta
      else if (index == 0 && column == 3) {
        _radioValues[3][2][7] = -1;
      } else if (index == 2 && column == 7) {
        _radioValues[3][0][3] = -1;
      }
      // light yellow
      else if (index == 1 && column == 6) {
        _radioValues[3][2][6] = -1;
      } else if (index == 2 && column == 6) {
        _radioValues[3][1][6] = -1;
      }
      // yellow
      else if (index == 1 && column == 7) {
        _radioValues[3][2][8] = -1;
      } else if (index == 2 && column == 8) {
        _radioValues[3][1][7] = -1;
      }
    }
    // Question 5 (Bicycle Improvements)
    else if (row == 4) {
      // red
