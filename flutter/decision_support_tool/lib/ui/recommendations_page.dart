  Widget _buildOptionsColumn(
    int categoryIndex,
    int columnType,
    List<String> options,
    double width,
    Color bgColor,
  ) {
    return Container(
      width: width,
      color: bgColor,
      padding: EdgeInsets.all(8.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        mainAxisAlignment: MainAxisAlignment.start,
        children: [
          for (var i = 0; i < options.length; i++)
            _buildOptionRow(categoryIndex, columnType, i, options[i]),
        ],
      ),
    );
  }

  Widget _buildOptionRow(
    int categoryIndex,
    int columnType,
    int optionIndex,
    String optionText,
  ) {
    double width = MediaQuery.of(context).size.width * 0.94;

    return Padding(
      padding: EdgeInsets.all(10.0),
      child: Wrap(
        children: [
          Radio(
            toggleable: true,
            value: optionIndex,
            groupValue: _radioValues[categoryIndex][columnType][optionIndex],
            onChanged: (int? value) {
              setState(() {
                if (_radioValues[categoryIndex][columnType][optionIndex] !=
                    value) {
                  _radioValues[categoryIndex][columnType][optionIndex] =
                      value ?? -1;
                  if (value != null && value != -1) {
                    _logicRadioValues(
                      _getColumnName(columnType),
                      categoryIndex,
                      optionIndex,
                    );
                  }
                } else {
                  _radioValues[categoryIndex][columnType][optionIndex] = -1;
                }
              });
            },
          ),
          Padding(padding: EdgeInsets.only(left: 10.0)),
          InkWell(
            onTap: () {
              setState(() {
                if (_radioValues[categoryIndex][columnType][optionIndex] !=
                    optionIndex) {
                  _radioValues[categoryIndex][columnType][optionIndex] =
                      optionIndex;
                  _logicRadioValues(
                    _getColumnName(columnType),
                    categoryIndex,
                    optionIndex,
                  );
                } else {
                  _radioValues[categoryIndex][columnType][optionIndex] = -1;
                }
              });
            },
            child: Container(
              padding: EdgeInsets.all(5.0),
              width: width * 0.15,
              child: Text(
                optionText,
                overflow: TextOverflow.clip,
                style: TextStyle(fontSize: 13.0),
              ),
            ),
          ),
        ],
      ),
    );
  }

  String _getColumnName(int columnType) {
    switch (columnType) {
      case 0:
        return 'good';
      case 1:
        return 'better';
      case 2:
        return 'best';
      default:
        return 'good';
    }
  }

