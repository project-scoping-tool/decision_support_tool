  Widget _buildCategoryRow(int categoryIndex) {
    final category =
        _viewModel.recommendationsInfo.s3_categories[categoryIndex];
    double width = MediaQuery.of(context).size.width * 0.94;
    bool dark = categoryIndex % 2 == 0;

    Color highSoftColor = Colors.green[50]!;
    Color highHardColor = Colors.green[200]!;
    Color lowSoftColor = Colors.grey[200]!;
    Color lowHardColor = Colors.blueGrey[100]!;

    Color goodColor, betterColor, bestColor, bgColor;

    if (dark) {
      goodColor = _viewModel.isHighlightingGoodColumn
          ? highHardColor
          : lowHardColor;
      betterColor = _viewModel.isHighlightingBetterColumn
          ? highHardColor
          : lowHardColor;
      bestColor = _viewModel.isHighlightingBestColumn
          ? highHardColor
          : lowHardColor;
      bgColor = lowHardColor;
    } else {
      goodColor = _viewModel.isHighlightingGoodColumn
          ? highSoftColor
          : lowSoftColor;
      betterColor = _viewModel.isHighlightingBetterColumn
          ? highSoftColor
          : lowSoftColor;
      bestColor = _viewModel.isHighlightingBestColumn
          ? highSoftColor
          : lowSoftColor;
      bgColor = lowSoftColor;
    }

    return Padding(
      padding: EdgeInsets.symmetric(
        horizontal: MediaQuery.of(context).size.width * 0.03,
      ),
      child: IntrinsicHeight(
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            _buildCategoryNameCell(
              categoryIndex,
              category.categoryTitle,
              width * 0.2 - 3.0,
              bgColor,
            ),
            Container(width: 3.0, color: Colors.white),
            _buildOptionsColumn(
              categoryIndex,
              0,
              category.goodHealth,
              width * 0.2 - 3.0,
              goodColor,
            ),
            Container(width: 3.0, color: Colors.white),
            _buildOptionsColumn(
              categoryIndex,
              1,
              category.betterHealth,
              width * 0.2 - 3.0,
              betterColor,
            ),
            Container(width: 3.0, color: Colors.white),
            _buildOptionsColumn(
              categoryIndex,
              2,
              category.bestHealth,
              width * 0.2 - 3.0,
              bestColor,
            ),
            Container(width: 3.0, color: Colors.white),
            _buildJustificationCell(categoryIndex, width * 0.2, bgColor),
          ],
        ),
      ),
    );
  }

